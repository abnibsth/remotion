import {chromium} from 'playwright-core';
import path from 'node:path';
import fs from 'node:fs/promises';
import {renderSettings} from './render-settings.mjs';
const {fps,directory}=renderSettings();
const composition=fps===60?'NotifikasiOverload60':'NotifikasiOverload';
await fs.mkdir(directory,{recursive:true});
const browser=await chromium.launch({executablePath:path.join(process.env.LOCALAPPDATA,'ms-playwright/chromium-1234/chrome-win64/chrome.exe'),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.goto(`http://localhost:3000/${composition}`,{waitUntil:'networkidle'});
await page.getByText(composition,{exact:true}).first().waitFor();
await page.waitForFunction(()=>document.querySelector('.no-stage'));
await page.keyboard.press('Space');
await page.waitForFunction(()=>Number(document.querySelector('.no-stage')?.getAttribute('data-time'))>.5);
await page.keyboard.press('Space');
await page.screenshot({path:path.join(directory,'studio-preview.png')});
const status=await page.evaluate(()=>({title:document.title,stage:!!document.querySelector('.no-stage'),time:document.querySelector('.no-stage')?.getAttribute('data-time'),body:document.body.innerText.slice(-1800)}));
await fs.writeFile(path.join(directory,'studio-check.json'),JSON.stringify({errors,status},null,2));
console.log(JSON.stringify({errors,stage:status.stage,time:status.time}));
await browser.close();
if(errors.length)process.exit(1);
