"""Original deterministic score. Run: python -I scripts/fix-one-bug/audio.py"""
import json
import subprocess
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'public/fix-one-bug/audio'
OUT.mkdir(parents=True,exist_ok=True)
SR=48000
N=20*SR
rng=np.random.default_rng(20261023)
stems={k:np.zeros((N,2)) for k in ['keys','success','errors','construction','reveal']}
def run(args):
    p=subprocess.run(['ffmpeg','-hide_banner','-nostdin','-y',*map(str,args)],capture_output=True)
    if p.returncode: raise RuntimeError(p.stderr.decode(errors='replace'))
    return p.stderr.decode(errors='replace')
def add(name,at,s,gain=1,pan=0):
    i=round(at*SR);n=min(len(s),N-i)
    stems[name][i:i+n]+=s[:n,None]*np.array([np.sqrt((1-pan)/2),np.sqrt((1+pan)/2)])[None,:]*gain
def hit(name,at,f=65,gain=.4,d=.25):
    t=np.arange(round(d*SR))/SR
    s=(np.sin(2*np.pi*(f*t+2*(1-np.exp(-t*40))))*np.exp(-t*18)+rng.normal(0,.14,len(t))*np.exp(-t*70))
    add(name,at,s*np.minimum(1,t*2000)*np.minimum(1,(d-t)*100),gain)
def tone(name,at,notes,d,gain=.1):
    t=np.arange(round(d*SR))/SR;e=np.minimum(1,t/.04)*np.minimum(1,(d-t)/.08)
    for i,n in enumerate(notes):
        f=440*2**((n-69)/12)
        s=sum(np.sin(2*np.pi*f*h*t)/h**1.4 for h in range(1,6))*e
        add(name,at,s,gain,(i%3-1)*.4)
for at in [.4,.7,1.1,1.5,3.3,18.35,19.65]:hit('keys',at,700,.065,.06)
tone('success',3.65,[76,80,83],.8,.10)
for at,n in [(4.25,72),(4.75,76),(5.25,79)]:tone('success',at,[n],.3,.08)
hit('errors',6.1,110,.6,.2)
for i in range(10):hit('errors',6.30+i*.13,160+i*31,.32,.18)
for i in range(22):
    at=10+i*.22
    hit('construction',at,50+(i%3)*15,.36,.20)
    if i%3==0:tone('construction',at,[38+(i%4)*2,50+(i%4)*2],.4,.07)
for at,ns in [(10,[38,50,57]),(11.2,[34,46,53]),(12.4,[31,43,55]),(13.6,[33,45,57]),(15.35,[38,50,57,62,66])]:
    tone('reveal',at,ns,min(1.15,16.5-at),.12 if at<15 else .19)
hit('reveal',15.35,38,.65,.7)
tone('keys',18.85,[83],.13,.12)
# Quiet, designed tension rather than a fake code soundtrack.
t=np.arange(3*SR)/SR
add('construction',0,np.sin(2*np.pi*55*t)*np.sin(np.pi*t/3)**2,.025)
for a in stems.values():a[round(16.5*SR):18*SR]=0;a[round(19.9*SR):]=0
peak=max(np.max(np.abs(sum(stems.values()))),1)
for name,a in stems.items():
    a/=peak
    raw=OUT/(name+'.f32');raw.write_bytes(a.astype('<f4').tobytes())
    run(['-f','f32le','-ar',SR,'-ac',2,'-i',raw,'-c:a','pcm_s24le',OUT/('stem-'+name+'.wav')]);raw.unlink()
mix=sum(stems.values());raw=OUT/'mix.f32';raw.write_bytes(mix.astype('<f4').tobytes())
run(['-f','f32le','-ar',SR,'-ac',2,'-i',raw,'-af','loudnorm=I=-14:TP=-2.5:LRA=11,volume=-1.15dB','-ar',SR,'-c:a','pcm_s24le',OUT/'mix.wav']);raw.unlink()
run(['-i',OUT/'mix.wav','-c:a','aac','-b:a','320k',OUT/'aac-qc.m4a'])
log=run(['-i',OUT/'aac-qc.m4a','-af','loudnorm=I=-14:TP=-1:LRA=11:print_format=json','-f','null','-'])
m=json.loads(log[log.rfind('{'):log.rfind('}')+1])
(OUT/'metrics.json').write_text(json.dumps(m,indent=2))
(OUT/'LICENSE.md').write_text('# Original procedural audio\n\nAll sounds and chords are original seeded mathematical synthesis; no external samples, recordings, voice or downloaded music. Generated by scripts/fix-one-bug/audio.py. To the extent copyright applies, audio and this generator are dedicated under CC0 1.0 Universal.\n\nFive time-aligned 48kHz stereo premaster stems are included. Use mix.wav for final edit; stems do not reconstruct loudness mastering exactly.\n')
assert abs(float(m['input_i'])+14)<1.0,m
assert float(m['input_tp'])<=-1,m
print(json.dumps(m,indent=2))
